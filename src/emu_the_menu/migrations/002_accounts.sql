-- Accounts, sign-in sessions and the sign-in throttle (ADR 0008).

-- An account signs in as one Eater, by that Eater's name. The role decides what it may change:
-- an Adult edits everything, a Teen marks Meals cooked and edits their own dislikes and diet.
CREATE TABLE accounts (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eater_id      integer NOT NULL UNIQUE REFERENCES eaters (id) ON DELETE CASCADE,
    role          text NOT NULL CHECK (role IN ('adult', 'teen')),
    password_hash text NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now()
);

-- The cookie holds a random token; only its SHA-256 is kept, so a copy of this table cannot be
-- used to sign in.
CREATE TABLE sessions (
    token_hash text PRIMARY KEY,
    account_id integer NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    csrf_token text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL
);
CREATE INDEX sessions_account ON sessions (account_id);

-- Failed sign-ins by the name tried (lowercased), whether or not such an account exists.
CREATE TABLE sign_in_failures (
    name_key       text PRIMARY KEY,
    failures       integer NOT NULL,
    last_failed_at timestamptz NOT NULL
);
